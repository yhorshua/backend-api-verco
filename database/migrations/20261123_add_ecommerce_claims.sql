CREATE TABLE IF NOT EXISTS EcommerceClaims (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  claim_code VARCHAR(40) NULL,
  storefront_id INT NOT NULL,
  claim_type ENUM('RECLAMO','QUEJA') NOT NULL,
  consumer_name VARCHAR(150) NOT NULL,
  document_type VARCHAR(20) NOT NULL,
  document_number VARCHAR(20) NOT NULL,
  consumer_address VARCHAR(255) NOT NULL,
  consumer_phone VARCHAR(30) NOT NULL,
  consumer_email VARCHAR(150) NOT NULL,
  is_minor TINYINT(1) NOT NULL DEFAULT 0,
  representative_name VARCHAR(150) NULL,
  representative_document VARCHAR(20) NULL,
  item_type ENUM('PRODUCTO','SERVICIO') NOT NULL,
  item_description VARCHAR(500) NOT NULL,
  amount DECIMAL(12,2) NOT NULL DEFAULT 0.00,
  order_code VARCHAR(30) NULL,
  detail TEXT NOT NULL,
  consumer_request TEXT NOT NULL,
  response_method ENUM('EMAIL','DOMICILIO') NOT NULL DEFAULT 'EMAIL',
  status ENUM('REGISTRADO','EN_ATENCION','RESPONDIDO','CERRADO') NOT NULL DEFAULT 'REGISTRADO',
  provider_actions TEXT NULL,
  provider_response TEXT NULL,
  responded_at DATETIME NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_ecommerce_claim_code (claim_code),
  KEY idx_ecommerce_claim_store_status_date (storefront_id, status, created_at),
  CONSTRAINT fk_ecommerce_claim_storefront FOREIGN KEY (storefront_id) REFERENCES Storefronts(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
